interface Draft {
  readonly files: RenderedFile[];
  readonly elements: CanonicalKnowledgeObject[];
  readonly missingInputs?: string[];
  readonly notes?: string[];
}

/** What would let Phoenix produce each artifact, named for the gap planner (FR-GAP-02). */
