// --- Registry -----------------------------------------------------------------------------------

const RENDERERS: Readonly<Record<OkfArtifactId, (view: BundleView) => Draft>> = {
  'logical-data-model': renderLogicalDataModel,
  domains: renderDomains,
  'personas-journeys': renderPersonasJourneys,
  screens: (view) => renderUnavailable('screens', 'Screens', view),
  'execution-flows': renderExecutionFlows,
  'architecture-c4': renderArchitectureC4,
  deployment: renderDeployment,
  'non-functional-requirements': (view) =>
    renderUnavailable('non-functional-requirements', 'Non-functional requirements', view),
  backlog: renderBacklog,
  'integrations-dataflows': renderIntegrations,
  'flow-to-journey': renderFlowToJourney,
};

function finish(id: OkfArtifactId, draft: Draft): RenderedArtifact {
  const definition = OKF_ARTIFACTS.find((a) => a.id === id)!;
  const seen = new Set<string>();
  const elements = draft.elements
    .filter((e) => (seen.has(e.identity.id) ? false : (seen.add(e.identity.id), true)))
    .map(traceOf);
  const status = !definition.modelled
    ? 'unavailable'
    : elements.length === 0
      ? 'empty'
      : 'rendered';
  const trace: RenderedFile = {
    path: 'trace.json',
    mediaType: 'application/json',
    content: `${JSON.stringify({ artifact: id, status, elements }, null, 2)}\n`,
  };
  return {
    id,
    label: definition.label,
    status,
    files: [...draft.files, trace],
    elements,
    missingInputs: draft.missingInputs ?? [],
    notes: draft.notes ?? [],
  };
}

/** Render one artifact. Pure and deterministic: the same bundle always gives the same bytes. */
export function renderArtifact(
  id: OkfArtifactId,
  bundle: BundleView | ConstructorParameters<typeof BundleView>[0],
): RenderedArtifact {
  const view = bundle instanceof BundleView ? bundle : new BundleView(bundle);
  return finish(id, RENDERERS[id](view));
}

/** All eleven artifacts, in the FRD's order. */
export function renderAllArtifacts(
  bundle: ConstructorParameters<typeof BundleView>[0],
): RenderedArtifact[] {
  const view = new BundleView(bundle);
  return OKF_ARTIFACTS.map((a) => renderArtifact(a.id, view));
}
