// --- 1. Logical data model: DBML + data dictionary (FR-OKF-01) ---------------------------------

const TABLE_NAME = /^Maps to table "([^"]+)"\.?$/;

function dbmlName(text: string): string {
  return `"${text.replace(/"/g, '\\"')}"`;
}

function dbmlNote(text: string): string {
  return `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\r?\n/g, ' ')}'`;
}

function renderLogicalDataModel(view: BundleView): Draft {
  const entities = view.ofKind('domain.entity');
  // Observed entities are physical/persistent structures; inferred
  // `domain.entity` objects are business concepts and are never drawn as
  // tables -- they are listed apart in the dictionary.
  const tables = entities.filter((e) => basisOf(e) === 'observed');
  const concepts = entities.filter((e) => basisOf(e) === 'derived');
  const tableIds = new Set(tables.map((t) => t.identity.id));

  const dbml: string[] = [
    `// Logical data model of ${view.bundle.systemId}, generated by Phoenix from the knowledge graph.`,
    '// Every table traces to source evidence; see trace.json. Types are as declared in source.',
    '',
  ];
  const refs: string[] = [];
  for (const table of tables) {
    const fields = arrayAttribute<FieldDefinition>(table, 'fields');
    const description = stringAttribute(table, 'description');
    dbml.push(`Table ${dbmlName(table.label)} {`);
    for (const field of fields) {
      const settings =
        field.required === true ? ' [not null]' : field.required === false ? ' [null]' : '';
      dbml.push(`  ${dbmlName(field.name)} ${dbmlName(field.type ?? 'unknown')}${settings}`);
    }
    if (fields.length === 0) dbml.push('  // no fields extracted');
    dbml.push(
      `  Note: ${dbmlNote(`${description ?? ''} ${provenanceLine(table).replace(/\*\*/g, '')}`.trim())}`,
    );
    dbml.push('}', '');

    for (const { relationship, target } of view.out(table.identity.id, 'hasAssociation')) {
      if (!tableIds.has(target.identity.id)) continue;
      const fieldName = relationship.attributes?.fieldName;
      const associationKind = relationship.attributes?.associationKind;
      const targetHasId = arrayAttribute<FieldDefinition>(target, 'fields').some(
        (f) => f.name === 'id',
      );
      const operator =
        associationKind === 'ManyToOne' ? '>' : associationKind === 'OneToOne' ? '-' : undefined;
      if (
        operator !== undefined &&
        typeof fieldName === 'string' &&
        fields.some((f) => f.name === fieldName) &&
        targetHasId
      ) {
        refs.push(
          `Ref: ${dbmlName(table.label)}.${dbmlName(fieldName)} ${operator} ${dbmlName(target.label)}.${dbmlName('id')} // ${String(associationKind)}`,
        );
      } else {
        // Join columns were not extracted: state the association, do not guess its keys.
        refs.push(
          `// ${table.label}${typeof fieldName === 'string' ? `.${fieldName}` : ''} -> ${target.label} (${String(associationKind ?? 'association')}): join columns not extracted`,
        );
      }
    }
  }
  dbml.push(...refs);

  const dictionary: string[] = header(
    'Data dictionary',
    view,
    `${tables.length} persistent entit${tables.length === 1 ? 'y' : 'ies'} observed in source; ${concepts.length} inferred business concept(s) listed separately.`,
  );
  for (const table of tables) {
    const tableName = TABLE_NAME.exec(stringAttribute(table, 'description') ?? '')?.[1];
    dictionary.push(`## ${table.label}`, '', `_${provenanceLine(table)}_`, '');
    if (tableName !== undefined) dictionary.push(`Physical table: \`${tableName}\``, '');
    const fields = arrayAttribute<FieldDefinition>(table, 'fields');
    if (fields.length > 0) {
      dictionary.push('| Field | Type | Required |', '| --- | --- | --- |');
      for (const f of fields) {
        dictionary.push(
          `| ${cell(f.name)} | ${cell(f.type)} | ${f.required === undefined ? 'not determined' : f.required ? 'yes' : 'no'} |`,
        );
      }
      dictionary.push('');
    } else {
      dictionary.push('No fields were extracted for this entity.', '');
    }
    const associations = view.out(table.identity.id, 'hasAssociation');
    for (const { relationship, target } of associations) {
      dictionary.push(
        `- Associated with **${target.label}** (${cell(String(relationship.attributes?.associationKind ?? 'association'))}${typeof relationship.attributes?.fieldName === 'string' ? ` via \`${relationship.attributes.fieldName}\`` : ''})`,
      );
    }
    const states = view.out(table.identity.id, 'hasState');
    for (const { target } of states) {
      dictionary.push(`- State **${target.label}** — _${provenanceLine(target)}_`);
    }
    dictionary.push('');
  }
  if (concepts.length > 0) {
    dictionary.push(
      '## Inferred business concepts (not physical tables)',
      '',
      'These were inferred from names and structure in the code. They are candidates for the business glossary and need review; none is a table.',
      '',
    );
    for (const concept of concepts) {
      dictionary.push(`- **${concept.label}** — _${provenanceLine(concept)}_`);
    }
  }

  const states = view.ofKind('domain.entity-state', 'domain.aggregate');
  return {
    files: [
      {
        path: 'data-model.dbml',
        mediaType: 'text/plain',
        content: `${dbml.join('\n').trimEnd()}\n`,
      },
      markdown('data-dictionary.md', dictionary),
    ],
    elements: [...tables, ...concepts, ...states],
    ...(tables.length === 0 ? { missingInputs: [ARTIFACT_INPUTS['logical-data-model']] } : {}),
  };
}

// --- 2. Domains & capabilities (FR-OKF-02) ------------------------------------------------------

function renderDomains(view: BundleView): Draft {
  const domains = view.ofKind('domain.domain');
  const aggregates = view.ofKind('domain.aggregate');
  const capabilities = view.ofKind('business.capability');
  const lines = header(
    'Domains & business capabilities',
    view,
    `${domains.length} declared domain(s), ${aggregates.length} aggregate(s), ${capabilities.length} inferred capability(ies).`,
  );

  lines.push('## Domains', '');
  if (domains.length === 0) {
    lines.push(
      'No domain or bounded context is declared in the analysed sources. The capabilities below are groupings Phoenix inferred from code structure — please confirm, rename or split them.',
      '',
    );
  }
  for (const domain of domains) {
    lines.push(`### ${domain.label}`, '', `_${provenanceLine(domain)}_`, '');
    const description = stringAttribute(domain, 'description');
    if (description !== undefined) lines.push(description, '');
    for (const { target } of view.out(domain.identity.id, 'contains')) {
      lines.push(`- contains **${target.label}** (${target.kind})`);
    }
    lines.push('');
  }

  if (aggregates.length > 0) {
    lines.push('## Aggregates', '');
    for (const aggregate of aggregates) {
      lines.push(`### ${aggregate.label}`, '', `_${provenanceLine(aggregate)}_`, '');
      for (const { target } of view.out(aggregate.identity.id, 'aggregateRoot')) {
        lines.push(`- root: **${target.label}**`);
      }
      for (const { target } of view.out(aggregate.identity.id, 'aggregateMember')) {
        lines.push(`- member: **${target.label}**`);
      }
      lines.push('');
    }
  }

  lines.push('## Business capabilities', '');
  if (capabilities.length === 0) lines.push('No business capability was inferred in this run.', '');
  for (const capability of capabilities) {
    lines.push(`### ${capability.label}`, '', `_${provenanceLine(capability)}_`, '');
    const description = stringAttribute(capability, 'description');
    if (description !== undefined) lines.push(description, '');
    const comprised = view.out(capability.identity.id, 'comprises').map((x) => x.target);
    if (comprised.length > 0) {
      lines.push(
        `Comprises: ${comprised
          .sort(byLabelThenId)
          .map((c) => `**${c.label}**${basisOf(c) === 'derived' ? ' (inferred)' : ''}`)
          .join(', ')}`,
        '',
      );
    }
    const realized = view.out(capability.identity.id, 'realizedBy').map((x) => x.target);
    if (realized.length > 0) {
      lines.push(
        `Realised in code by: ${realized
          .sort(byLabelThenId)
          .map((c) => `\`${c.label}\``)
          .join(', ')}`,
        '',
      );
    }
  }

  const elements = [...domains, ...aggregates, ...capabilities];
  return {
    files: [markdown('domains.md', lines)],
    elements,
    ...(domains.length === 0 ? { missingInputs: [ARTIFACT_INPUTS.domains] } : {}),
  };
}

// --- 3. Personas & journeys (FR-OKF-03) ---------------------------------------------------------

function renderPersonasJourneys(view: BundleView): Draft {
  const personas = view.ofKind('journey.persona');
  const journeys = view.ofKind('journey.journey');
  const lines = header(
    'Personas & journeys',
    view,
    `${personas.length} persona(s), ${journeys.length} journey(s).`,
  );

  lines.push('## Personas', '');
  if (personas.length === 0) {
    lines.push(
      'No persona appears in the analysed sources. Code alone rarely names who uses a system: a short description of the user roles (or the access-control configuration) would let Phoenix attach journeys to the people who perform them.',
      '',
    );
  }
  for (const persona of personas) {
    lines.push(`### ${persona.label}`, '', `_${provenanceLine(persona)}_`, '');
    const role = stringAttribute(persona, 'role');
    const description = stringAttribute(persona, 'description');
    if (role !== undefined) lines.push(`Role: ${role}`, '');
    if (description !== undefined) lines.push(description, '');
    for (const goal of arrayAttribute<string>(persona, 'goals')) lines.push(`- Goal: ${goal}`);
    for (const pain of arrayAttribute<string>(persona, 'painPoints'))
      lines.push(`- Pain point: ${pain}`);
    lines.push('');
  }

  lines.push('## Journeys', '');
  if (journeys.length === 0) lines.push('No journey was identified in this run.', '');
  for (const journey of journeys) {
    lines.push(`### ${journey.label}`, '', `_${provenanceLine(journey)}_`, '');
    const purpose = stringAttribute(journey, 'purpose');
    if (purpose !== undefined) lines.push(purpose, '');
    const performers = view.out(journey.identity.id, 'hasPersona').map((x) => x.target.label);
    lines.push(
      performers.length > 0
        ? `Performed by: ${performers.join(', ')}`
        : 'Performed by: _not determined — no persona is linked to this journey_',
      '',
    );
    const flows = view.in(journey.identity.id, 'supports').map((x) => x.source);
    for (const flow of flows) lines.push(`- Realised by flow **${flow.label}**`);
    lines.push('');
  }

  const missing: string[] = [];
  if (personas.length === 0 || journeys.length === 0)
    missing.push(ARTIFACT_INPUTS['personas-journeys']);
  return {
    files: [markdown('personas-journeys.md', lines)],
    elements: [...personas, ...journeys],
    missingInputs: missing,
  };
}

// --- 5. Execution flows (FR-OKF-05) -------------------------------------------------------------

function renderExecutionFlows(view: BundleView): Draft {
  const flows = view.ofKind('journey.flow');
  const lines = header('Execution flows', view, `${flows.length} flow(s).`);
  const elements: CanonicalKnowledgeObject[] = [...flows];

  if (flows.length === 0) lines.push('No execution flow was identified in this run.', '');
  for (const flow of flows) {
    lines.push(`## ${flow.label}`, '', `_${provenanceLine(flow)}_`, '');
    const description = stringAttribute(flow, 'description');
    if (description !== undefined) lines.push(description, '');
    const steps = view
      .out(flow.identity.id, 'contains')
      .sort((a, b) => {
        const ao = Number(a.relationship.attributes?.order ?? Number.MAX_SAFE_INTEGER);
        const bo = Number(b.relationship.attributes?.order ?? Number.MAX_SAFE_INTEGER);
        return ao - bo || byLabelThenId(a.target, b.target);
      })
      .map((x) => x.target);
    if (steps.length === 0) {
      lines.push('No steps are recorded for this flow.', '');
      continue;
    }
    const ids = new IdAllocator('n');
    const chart = ['```mermaid', 'flowchart LR'];
    steps.forEach((step, index) => {
      chart.push(`  ${ids.get(step.identity.id)}["${mermaidLabel(step.label)}"]`);
      if (index > 0)
        chart.push(`  ${ids.get(steps[index - 1]!.identity.id)} --> ${ids.get(step.identity.id)}`);
    });
    lines.push(
      '| # | Step | Reads | Writes | Transitions to | Provenance |',
      '| --- | --- | --- | --- | --- | --- |',
    );
    steps.forEach((step, index) => {
      elements.push(step);
      const reads = view.out(step.identity.id, 'readsEntity').map((x) => x.target);
      const writes = view.out(step.identity.id, 'writesEntity').map((x) => x.target);
      const transitions = view.out(step.identity.id, 'triggersTransition').map((x) => x.target);
      for (const entity of reads) {
        chart.push(
          `  ${ids.get(step.identity.id)} -. reads .-> ${ids.get(entity.identity.id)}[("${mermaidLabel(entity.label)}")]`,
        );
      }
      for (const entity of writes) {
        chart.push(
          `  ${ids.get(step.identity.id)} == writes ==> ${ids.get(entity.identity.id)}[("${mermaidLabel(entity.label)}")]`,
        );
      }
      lines.push(
        `| ${index + 1} | ${cell(step.label)} | ${cell(reads.map((r) => r.label).join(', '))} | ${cell(writes.map((w) => w.label).join(', '))} | ${cell(transitions.map((t) => t.label).join(', '))} | ${cell(provenanceLine(step))} |`,
      );
    });
    chart.push('```');
    lines.push('', ...chart, '');
  }

  return {
    files: [markdown('execution-flows.md', lines)],
    elements,
    ...(flows.length === 0 ? { missingInputs: [ARTIFACT_INPUTS['execution-flows']] } : {}),
  };
}

// --- 6. C4 architecture: Structurizr DSL (FR-OKF-06) --------------------------------------------

function dsl(text: string): string {
  return `"${text.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\r?\n/g, ' ')}"`;
}

function renderArchitectureC4(view: BundleView): Draft {
  const systems = view.ofKind('architecture.system');
  const declaredContainers = view.ofKind('architecture.container');
  const components = view.ofKind('architecture.component');
  // A deployment unit IS a C4 container (a separately deployable unit), so
  // when no container is declared, the IaC-extracted units stand in -- and
  // the output says that is where they came from.
  const units = declaredContainers.length === 0 ? view.ofKind('deployment.unit') : [];
  const containers = [...declaredContainers, ...units];
  const notes: string[] = [];
  if (units.length > 0) {
    notes.push(
      `Containers are the ${units.length} deployment unit(s) extracted from deployment descriptors; no container is declared in architecture documentation.`,
    );
  }

  const system = systems.length === 1 ? systems[0] : undefined;
  const systemName = system?.label ?? view.bundle.systemId;
  const ids = new IdAllocator('c');
  const placed = new Set<string>();
  const model: string[] = [
    `    system = softwareSystem ${dsl(systemName)} ${dsl((system === undefined ? undefined : stringAttribute(system, 'description')) ?? 'The system under analysis.')} {`,
  ];
  for (const container of containers) {
    const id = ids.get(container.identity.id);
    const description =
      stringAttribute(container, 'responsibility') ??
      (container.kind === 'deployment.unit'
        ? `Deployment unit (${String(container.attributes.workload ?? 'workload')})`
        : '');
    const technology =
      stringAttribute(container, 'technology') ?? stringAttribute(container, 'image') ?? '';
    const inner: string[] = [];
    for (const { target } of view.out(container.identity.id, 'contains')) {
      if (target.kind !== 'architecture.component') continue;
      placed.add(target.identity.id);
      inner.push(
        `        ${ids.get(target.identity.id)} = component ${dsl(target.label)} ${dsl(stringAttribute(target, 'responsibility') ?? '')}`,
      );
    }
    model.push(
      `      ${id} = container ${dsl(container.label)} ${dsl(description)} ${dsl(technology)}${inner.length > 0 ? ' {' : ''}`,
      ...inner,
      ...(inner.length > 0 ? ['      }'] : []),
    );
  }
  model.push('    }');
  const unplaced = components.filter((c) => !placed.has(c.identity.id));
  if (unplaced.length > 0) {
    notes.push(
      `${unplaced.length} component(s) have no recorded container and are listed in c4.md only: ${unplaced.map((c) => c.label).join(', ')}.`,
    );
  }

  const edges: string[] = [];
  for (const container of containers) {
    for (const kind of ['communicatesWith', 'dependsOn']) {
      for (const { target } of view.out(container.identity.id, kind)) {
        if (!containers.some((c) => c.identity.id === target.identity.id)) continue;
        edges.push(
          `    ${ids.get(container.identity.id)} -> ${ids.get(target.identity.id)} ${dsl(kind === 'dependsOn' ? 'depends on' : 'communicates with')}`,
        );
      }
    }
  }

  const workspace = [
    `workspace ${dsl(`${systemName} — Phoenix`)} ${dsl('Generated from the Phoenix knowledge graph. Provenance for every element is in trace.json and c4.md.')} {`,
    '  model {',
    ...model,
    ...edges,
    '  }',
    '  views {',
    '    systemContext system "context" {',
    '      include *',
    '      autolayout lr',
    '    }',
    ...(containers.length > 0
      ? ['    container system "containers" {', '      include *', '      autolayout lr', '    }']
      : []),
    '  }',
    '}',
  ];

  const lines = header(
    'C4 architecture',
    view,
    `${systems.length} declared system(s), ${containers.length} container(s), ${components.length} component(s). The Structurizr DSL is in workspace.dsl.`,
  );
  if (system === undefined) {
    lines.push(
      systems.length > 1
        ? `More than one system is declared (${systems.map((s) => s.label).join(', ')}); the workspace is named after the analysed system id instead of choosing one.`
        : `No system is declared in the sources; the workspace is named after the analysed system id \`${view.bundle.systemId}\`.`,
      '',
    );
  }
  if (containers.length === 0) {
    lines.push(
      'No container could be identified: neither architecture documentation nor deployment descriptors were found. Only the system context is drawn.',
      '',
    );
  }
  for (const note of notes) lines.push(`> ${note}`, '');
  for (const element of [...systems, ...containers, ...components]) {
    lines.push(`- **${element.label}** (${element.kind}) — _${provenanceLine(element)}_`);
  }

  return {
    files: [
      { path: 'workspace.dsl', mediaType: 'text/plain', content: `${workspace.join('\n')}\n` },
      markdown('c4.md', lines),
    ],
    elements: [...systems, ...containers, ...components],
    notes,
    ...(containers.length === 0 ? { missingInputs: [ARTIFACT_INPUTS['architecture-c4']] } : {}),
  };
}

// --- 7. Deployment (FR-OKF-07) ------------------------------------------------------------------

function renderDeployment(view: BundleView): Draft {
  const units = view.ofKind('deployment.unit');
  const environments = view.ofKind('deployment.environment');
  const lines = header(
    'Deployment topology',
    view,
    `${units.length} deployment unit(s) in ${environments.length} declared environment(s), from deployment descriptors.`,
  );
  if (units.length === 0) {
    lines.push(
      'No deployment descriptor (Dockerfile, docker-compose, Kubernetes manifest) was found, so the deployment topology is unknown.',
      '',
    );
    return {
      files: [markdown('deployment.md', lines)],
      elements: [...environments],
      missingInputs: [ARTIFACT_INPUTS.deployment],
    };
  }

  const ids = new IdAllocator('d');
  const chart = ['```mermaid', 'flowchart TB'];
  const environmentOf = new Map<string, CanonicalKnowledgeObject>();
  for (const unit of units) {
    const env = view.out(unit.identity.id, 'runsIn')[0]?.target;
    if (env !== undefined) environmentOf.set(unit.identity.id, env);
  }
  for (const env of environments) {
    chart.push(`  subgraph ${ids.get(env.identity.id)}["${mermaidLabel(env.label)}"]`);
    for (const unit of units.filter(
      (u) => environmentOf.get(u.identity.id)?.identity.id === env.identity.id,
    )) {
      chart.push(`    ${ids.get(unit.identity.id)}["${mermaidLabel(unit.label)}"]`);
    }
    chart.push('  end');
  }
  for (const unit of units.filter((u) => !environmentOf.has(u.identity.id))) {
    chart.push(`  ${ids.get(unit.identity.id)}["${mermaidLabel(unit.label)}"]`);
  }
  for (const unit of units) {
    for (const { target } of view.out(unit.identity.id, 'dependsOn')) {
      if (target.kind !== 'deployment.unit') continue;
      chart.push(`  ${ids.get(unit.identity.id)} --> ${ids.get(target.identity.id)}`);
    }
  }
  chart.push('```');

  lines.push(
    '| Unit | Environment | Image | Ports | Replicas | Declared in | Provenance |',
    '| --- | --- | --- | --- | --- | --- | --- |',
  );
  for (const unit of units) {
    lines.push(
      `| ${cell(unit.label)} | ${cell(environmentOf.get(unit.identity.id)?.label ?? 'none declared')} | ${cell(stringAttribute(unit, 'image'))} | ${cell(arrayAttribute<string>(unit, 'ports').join(', '))} | ${cell(typeof unit.attributes.replicas === 'number' ? unit.attributes.replicas : undefined)} | ${cell(String(unit.attributes.sourceFormat ?? ''))} | ${cell(provenanceLine(unit))} |`,
    );
  }
  lines.push('', ...chart, '');
  return { files: [markdown('deployment.md', lines)], elements: [...units, ...environments] };
}

// --- 9. Backlog (FR-OKF-09) ---------------------------------------------------------------------

const ISSUE_TYPE_ORDER = ['epic', 'feature', 'story', 'task', 'bug', 'sub-task', 'subtask'];

function renderBacklog(view: BundleView): Draft {
  const issues = view.ofKind('workitem.issue');
  const lines = header(
    'Backlog — epics, features & stories',
    view,
    `${issues.length} work item(s) from the connected tracker.`,
  );
  if (issues.length === 0) {
    lines.push(
      'No issue tracker was connected for this run, so there is no backlog to show. Phoenix does not generate backlog items from code.',
      '',
    );
    return {
      files: [markdown('backlog.md', lines)],
      elements: [],
      missingInputs: [ARTIFACT_INPUTS.backlog],
    };
  }
  const typeOf = (o: CanonicalKnowledgeObject) => stringAttribute(o, 'issueType') ?? 'Unspecified';
  const rank = (type: string) => {
    const i = ISSUE_TYPE_ORDER.indexOf(type.toLowerCase());
    return i === -1 ? ISSUE_TYPE_ORDER.length : i;
  };
  const types = [...new Set(issues.map(typeOf))].sort(
    (a, b) => rank(a) - rank(b) || compareCodeUnits(a, b),
  );
  for (const type of types) {
    lines.push(`## ${type}`, '');
    for (const issue of issues.filter((i) => typeOf(i) === type)) {
      lines.push(`### ${issue.label}`, '', `_${provenanceLine(issue)}_`, '');
      lines.push(
        `Status: ${stringAttribute(issue, 'status') ?? 'unknown'} (as reported by the tracker when captured)${stringAttribute(issue, 'priority') === undefined ? '' : ` · Priority: ${stringAttribute(issue, 'priority')}`}`,
      );
      const labels = arrayAttribute<string>(issue, 'labels');
      if (labels.length > 0) lines.push(`Labels: ${labels.join(', ')}`);
      lines.push('');
      const description = stringAttribute(issue, 'description');
      if (description !== undefined) lines.push(description, '');
      for (const kind of ['contains', 'relatesTo']) {
        for (const { target } of view.out(issue.identity.id, kind)) {
          lines.push(`- ${kind === 'contains' ? 'Contains' : 'Relates to'} **${target.label}**`);
        }
      }
      lines.push('');
    }
  }
  return { files: [markdown('backlog.md', lines)], elements: issues };
}

// --- 10. Integrations & data flows (FR-OKF-10) --------------------------------------------------

interface Operation {
  readonly name: string;
  readonly description?: string;
}

function renderIntegrations(view: BundleView): Draft {
  const apis = view.ofKind('integration.api');
  const interfaces = view.ofKind('integration.interface');
  const integrations = view.ofKind('integration.integration');
  const dataflows = view.ofKind('integration.dataflow');
  const lines = header(
    'Integrations & data flows',
    view,
    `${apis.length} API(s), ${interfaces.length} interface(s), ${integrations.length} external integration(s), ${dataflows.length} data flow(s).`,
  );

  const ids = new IdAllocator('i');
  const chart = ['```mermaid', 'flowchart LR'];
  lines.push('## APIs', '');
  if (apis.length === 0) lines.push('No API was identified in this run.', '');
  for (const api of apis) {
    lines.push(`### ${api.label}`, '', `_${provenanceLine(api)}_`, '');
    const operations = arrayAttribute<Operation>(api, 'operations');
    if (operations.length > 0) {
      lines.push('| Operation | Detail |', '| --- | --- |');
      for (const op of operations) lines.push(`| ${cell(op.name)} | ${cell(op.description)} |`);
      lines.push('');
    }
    const uses = view.out(api.identity.id, 'dependsOn').map((x) => x.target);
    const distinct = [...new Map(uses.map((u) => [u.identity.id, u])).values()].sort(byLabelThenId);
    if (distinct.length > 0) {
      lines.push(`Data used: ${distinct.map((d) => `**${d.label}**`).join(', ')}`, '');
      chart.push(`  ${ids.get(api.identity.id)}["${mermaidLabel(api.label)}"]`);
      for (const d of distinct) {
        chart.push(
          `  ${ids.get(api.identity.id)} --> ${ids.get(d.identity.id)}[("${mermaidLabel(d.label)}")]`,
        );
      }
    }
  }

  lines.push('## External integrations', '');
  if (integrations.length === 0) {
    lines.push(
      'No call to an external system was identified. If the system talks to others (REST clients, queues, files), their configuration would let Phoenix map them.',
      '',
    );
  }
  for (const integration of integrations) {
    lines.push(
      `- **${integration.label}** — ${cell(String(integration.attributes.interactionType ?? 'direction unknown'))}${stringAttribute(integration, 'protocol') === undefined ? '' : ` over ${stringAttribute(integration, 'protocol')}`} — _${provenanceLine(integration)}_`,
    );
    chart.push(`  ${ids.get(integration.identity.id)}{{"${mermaidLabel(integration.label)}"}}`);
  }
  lines.push('');
  if (interfaces.length > 0) {
    lines.push('## Interfaces', '');
    for (const i of interfaces)
      lines.push(
        `- **${i.label}**${stringAttribute(i, 'protocol') === undefined ? '' : ` (${stringAttribute(i, 'protocol')})`} — _${provenanceLine(i)}_`,
      );
    lines.push('');
  }
  if (dataflows.length > 0) {
    lines.push('## Data flows', '');
    for (const f of dataflows)
      lines.push(
        `- **${f.label}**${stringAttribute(f, 'data') === undefined ? '' : ` carries ${stringAttribute(f, 'data')}`} — _${provenanceLine(f)}_`,
      );
    lines.push('');
  }
  chart.push('```');
  if (chart.length > 3) lines.push('## Diagram', '', ...chart, '');

  const elements = [...apis, ...interfaces, ...integrations, ...dataflows];
  return {
    files: [markdown('integrations.md', lines)],
    elements,
    ...(elements.length === 0
      ? { missingInputs: [ARTIFACT_INPUTS['integrations-dataflows']] }
      : {}),
  };
}

// --- 11. Flow-to-journey (FR-OKF-11) ------------------------------------------------------------

function renderFlowToJourney(view: BundleView): Draft {
  const flows = view.ofKind('journey.flow');
  const journeys = view.ofKind('journey.journey');
  const lines = header(
    'Flow-to-journey relationships',
    view,
    `${flows.length} flow(s), ${journeys.length} journey(s).`,
  );
  const linked = new Set<string>();
  lines.push('| Flow | Supports journey | Provenance of the flow |', '| --- | --- | --- |');
  for (const flow of flows) {
    const supported = view.out(flow.identity.id, 'supports').map((x) => x.target);
    for (const journey of supported) {
      linked.add(journey.identity.id);
      lines.push(
        `| ${cell(flow.label)} | ${cell(journey.label)} | ${cell(provenanceLine(flow))} |`,
      );
    }
    if (supported.length === 0)
      lines.push(`| ${cell(flow.label)} | _no journey linked_ | ${cell(provenanceLine(flow))} |`);
  }
  const orphanJourneys = journeys.filter((j) => !linked.has(j.identity.id));
  if (orphanJourneys.length > 0) {
    lines.push('', `Journeys with no flow: ${orphanJourneys.map((j) => j.label).join(', ')}.`);
  }
  const elements = [...flows, ...journeys];
  return {
    files: [markdown('flow-to-journey.md', lines)],
    elements,
    ...(flows.length === 0 || journeys.length === 0
      ? { missingInputs: [ARTIFACT_INPUTS['flow-to-journey']] }
      : {}),
  };
}

