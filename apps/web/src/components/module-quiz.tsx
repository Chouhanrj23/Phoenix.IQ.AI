import { useState, type JSX } from 'react';
import { CheckCircle2, Lock, X } from 'lucide-react';
import { Button } from './ui/button.js';
import {
  QUIZ_LEVELS,
  getQuizQuestions,
  isModuleQuizComplete,
  levelScore,
  type ModuleQuizState,
  type QuizLevelId,
} from '../lib/module-quiz.js';

interface ModuleQuizProps {
  moduleName: string;
  state: ModuleQuizState;
  onChange: (state: ModuleQuizState) => void;
  onClose: () => void;
}

export function ModuleQuiz({ moduleName, state, onChange, onClose }: ModuleQuizProps): JSX.Element {
  const firstOpen = QUIZ_LEVELS.find((level) => !state.completed.includes(level.id));
  const [active, setActive] = useState<QuizLevelId>(firstOpen?.id ?? 'introductory');

  const complete = isModuleQuizComplete(state);
  const isUnlocked = (index: number): boolean =>
    index === 0 || state.completed.includes(QUIZ_LEVELS[index - 1]!.id);
  const activeLevel = QUIZ_LEVELS.find((level) => level.id === active)!;
  const questions = getQuizQuestions(moduleName, active);
  const answers = state.answers[active] ?? {};
  const levelDone = state.completed.includes(active);
  const allAnswered = questions.every((_, index) => answers[index] !== undefined);

  function choose(questionIndex: number, option: number): void {
    if (levelDone) return;
    onChange({
      ...state,
      answers: { ...state.answers, [active]: { ...answers, [questionIndex]: option } },
    });
  }

  function submitLevel(): void {
    const levels: readonly (typeof QUIZ_LEVELS)[number][] = QUIZ_LEVELS;
    const next = levels[activeLevel.number];
    onChange({ ...state, completed: [...state.completed, active] });
    if (next) setActive(next.id);
  }

  return (
    <div
      className="fixed inset-0 z-50 flex items-center justify-center bg-slate-900/40 p-4"
      role="dialog"
      aria-modal="true"
      aria-label={`${moduleName} quiz`}
    >
      <div className="flex max-h-[90vh] w-full max-w-2xl flex-col rounded-xl bg-white shadow-2xl">
        <div className="flex items-start justify-between border-b border-slate-100 p-5">
          <div>
            <h2 className="text-lg font-semibold">{moduleName} quiz</h2>
            <p className="text-xs text-slate-500">
              Sample questions. They will be generated by the LLM from this module&apos;s documents.
            </p>
          </div>
          <button
            type="button"
            onClick={onClose}
            aria-label="Close quiz"
            className="text-slate-400 hover:text-slate-700"
          >
            <X className="h-5 w-5" />
          </button>
        </div>

        <div className="flex flex-wrap gap-2 border-b border-slate-100 px-5 py-3">
          {QUIZ_LEVELS.map((level, index) => {
            const unlocked = isUnlocked(index);
            const done = state.completed.includes(level.id);
            return (
              <button
                key={level.id}
                type="button"
                disabled={!unlocked}
                onClick={() => setActive(level.id)}
                className={`flex items-center gap-1.5 rounded-md px-3 py-1.5 text-xs font-medium transition-colors ${
                  active === level.id
                    ? 'bg-[#00338D] text-white'
                    : unlocked
                      ? 'border border-slate-200 text-slate-600 hover:bg-blue-50'
                      : 'cursor-not-allowed border border-slate-100 text-slate-300'
                }`}
              >
                {done ? (
                  <CheckCircle2 className="h-3.5 w-3.5" />
                ) : !unlocked ? (
                  <Lock className="h-3.5 w-3.5" />
                ) : null}
                Level {level.number} · {level.name}
              </button>
            );
          })}
        </div>

        <div className="space-y-5 overflow-y-auto p-5">
          {complete ? (
            <div className="rounded-md border border-emerald-200 bg-emerald-50 px-3 py-2 text-sm font-medium text-emerald-700">
              Quiz completed for {moduleName}.
            </div>
          ) : null}
          {questions.map((question, index) => (
            <fieldset key={question.prompt}>
              <legend className="mb-2 text-sm font-medium text-slate-800">
                {index + 1}. {question.prompt}
              </legend>
              <div className="space-y-1.5">
                {question.options.map((option, optionIndex) => (
                  <label
                    key={option}
                    className={`flex items-center gap-2 rounded-md border px-3 py-2 text-sm ${
                      answers[index] === optionIndex
                        ? 'border-[#00338D] bg-blue-50'
                        : 'border-slate-200 hover:bg-slate-50'
                    } ${levelDone ? 'cursor-default' : 'cursor-pointer'}`}
                  >
                    <input
                      type="radio"
                      name={`${active}-${index}`}
                      checked={answers[index] === optionIndex}
                      disabled={levelDone}
                      onChange={() => choose(index, optionIndex)}
                    />
                    {option}
                  </label>
                ))}
              </div>
            </fieldset>
          ))}
        </div>

        <div className="flex items-center justify-between border-t border-slate-100 p-4">
          <p className="text-xs text-slate-500">
            {levelDone
              ? `Level ${activeLevel.number} completed · score ${levelScore(state, moduleName, active).correct}/${questions.length}`
              : `${Object.keys(answers).length} of ${questions.length} answered`}
          </p>
          {levelDone ? (
            <Button type="button" size="sm" onClick={onClose}>
              Close
            </Button>
          ) : (
            <Button
              type="button"
              size="sm"
              disabled={!allAnswered}
              className="bg-[#00338D] hover:bg-[#002a73]"
              onClick={submitLevel}
            >
              {activeLevel.number < QUIZ_LEVELS.length
                ? 'Submit & unlock next level'
                : 'Submit & finish quiz'}
            </Button>
          )}
        </div>
      </div>
    </div>
  );
}
